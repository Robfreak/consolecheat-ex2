export const RTL = new Set<Lang>(["ar", "he"]);

const ids = new Set<string>(languageOptions.map((item) => item.id));

export function isLang(value: string | null): value is Lang {
  return value !== null && ids.has(value);
}

export function detectLang(tags: readonly string[]): Lang {
  for (const tag of tags) {
    const lower = tag.toLowerCase();
    if (lower === "zh-tw" || lower === "zh-hk" || lower === "zh-hant" || lower.startsWith("zh-hant")) return "zh-Hant";
    if (lower.startsWith("zh")) return "zh";
    if (lower === "nb" || lower === "nn" || lower.startsWith("no")) return "no";
    const base = lower.split("-")[0] ?? "";
    if (isLang(base)) return base;
  }
  return "de";
}

export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}
